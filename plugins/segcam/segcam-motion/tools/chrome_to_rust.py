#!/usr/bin/env python3
"""Converts segcam's baked window chrome (ae/core/Chrome.h, written by its
tools/chrome/bake.py) into src/chrome.rs. The data is pixels read out of real macOS
windows; this only changes the syntax.

    python3 tools/chrome_to_rust.py ~/segcam/ae/core/Chrome.h > src/chrome.rs
"""

import re
import sys


def rust_char(c):
    c = c.replace("\\u2026", "…")
    return "'\\''" if c == "'" else f"'{c}'"


def main(path):
    src = open(path, encoding="utf-8").read()
    out = [
        "//! segcam's window chrome, as macOS draws it for a segment's window: the title bar's",
        "//! pixel rows and corners, its three buttons, and the title glyphs as ink coverage,",
        "//! read out of real windows at 1x. Generated by `tools/chrome_to_rust.py` from segcam's",
        "//! `ae/core/Chrome.h`; do not edit by hand.",
        "",
        "#![allow(dead_code)]",
        "",
    ]

    types = {"int": "i32", "float": "f32", "double": "f64"}
    for kind, body in re.findall(r"^constexpr (int|float|double) ([^;\[]+);", src, re.M):
        for item in body.split(","):
            name, value = (s.strip() for s in item.split("="))
            value = value.rstrip("f") if kind == "float" else value
            out.append(f"pub const {screaming(name)}: {types[kind]} = {value};")

    for name, size, values in re.findall(
        r"^constexpr uint8_t (\w+)\[([^\]]+)\] = \{([^}]*)\};", src, re.M
    ):
        count = eval(size)  # "14 * 14 * 3"
        items = [v.strip() for v in values.split(",") if v.strip()]
        assert len(items) == count, (name, len(items), count)
        out.append(f"pub const {screaming(name)}: [u8; {count}] = [{', '.join(items)}];")

    out += [
        "",
        "pub struct Glyph {",
        "    pub ch: char,",
        "    pub advance: f64,",
        "    pub ink_min: f64,",
        "    pub ink_max: f64,",
        "    pub offset: i32,",
        "    pub cols: i32,",
        "    pub coverage: &'static [u8],",
        "}",
        "",
        "pub const GLYPHS: &[Glyph] = &[",
    ]
    table = re.search(r"kGlyphs\[\] = \{(.*?)\n\};", src, re.S).group(1)
    for ch, adv, lo, hi, off, cols, cov in re.findall(
        r"\{U'(.+?)', ([-\d.]+), ([-\d.]+), ([-\d.]+), (\d+), (\d+), (\w+)\}", table
    ):
        out.append(
            f"    Glyph {{ ch: {rust_char(ch)}, advance: {adv}, ink_min: {lo}, ink_max: {hi}, "
            f"offset: {off}, cols: {cols}, coverage: &{screaming(cov)} }},"
        )
    out += ["];", "", "pub struct Kern {", "    pub a: char,", "    pub b: char,", "    pub amount: f64,", "}", ""]
    kerns = re.search(r"kKerning\[\] = \{(.*?)\};", src).group(1)
    out.append("pub const KERNING: &[Kern] = &[")
    for a, b, amount in re.findall(r"\{U'(.+?)', U'(.+?)', ([-\d.]+)\}", kerns):
        out.append(f"    Kern {{ a: {rust_char(a)}, b: {rust_char(b)}, amount: {amount} }},")
    out.append("];")
    hashes = re.search(r"kHashKern\[\] = \{([^}]*)\};", src).group(1)
    items = [v.strip() for v in hashes.split(",")]
    out.append("/// Kerning after '#' before each digit 0-9, then '.'.")
    out.append(f"pub const HASH_KERN: [f64; {len(items)}] = [{', '.join(items)}];")
    print("\n".join(out))


def screaming(name):
    """kCornerTL_W -> CORNER_TL_W, kGlyphD0 -> GLYPH_D0."""
    name = re.sub(r"^k", "", name)
    name = re.sub(r"(?<=[a-z0-9])(?=[A-Z])", "_", name)
    return name.upper().replace("__", "_")


if __name__ == "__main__":
    main(sys.argv[1])
