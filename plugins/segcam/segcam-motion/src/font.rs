//! A 5x7 bitmap font, so labels need no text system from the host OS. It covers what segcam
//! ever writes (letters, digits, '#', '.', '-', ':') and draws anything else as '?'.

pub const GLYPH_WIDTH: i32 = 5;
pub const GLYPH_HEIGHT: i32 = 7;
/// One column of spacing.
pub const ADVANCE: i32 = 6;

/// Seven rows, top first; bit 4 of each row is the leftmost column.
pub fn glyph(c: char) -> &'static [u8; 7] {
    let i = c as usize;
    &TABLE[if i < 128 { i } else { b'?' as usize }]
}

