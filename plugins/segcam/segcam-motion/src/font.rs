const FALLBACK: usize = b'?' as usize;

/// Every ASCII code's rows, '?' for the ones the font doesn't draw. Built at compile time.
static TABLE: [[u8; 7]; 128] = build();

const fn build() -> [[u8; 7]; 128] {
    let mut table = [[0u8; 7]; 128];
    let mut present = [false; 128];
    let mut g = 0;
    while g < GLYPHS.len() {
        let (c, rows) = GLYPHS[g];
        let mut r = 0;
        while r < 7 {
            let bits = rows[r].as_bytes();
            let mut value = 0u8;
            let mut col = 0;
            while col < 5 {
                value = (value << 1) | (bits[col] == b'1') as u8;
                col += 1;
            }
            table[c as usize][r] = value;
            r += 1;
        }
        present[c as usize] = true;
        g += 1;
    }
    let mut i = 0;
    while i < 128 {
        if !present[i] {
            table[i] = table[FALLBACK];
        }
        i += 1;
    }
    table
}
